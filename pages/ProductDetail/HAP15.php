                if (
                    href.startsWith("#") ||
                    href.startsWith("javascript:") ||
                    this.target === "_blank"
                ) {
                    return;
                }

                e.preventDefault();

                loader.classList.add("show");

                setTimeout(() => {
                    window.location.href = href;
                }, 500);

            });

        });

    });

